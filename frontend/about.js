// 表示用のテキストを返す（symbol = /api/price の symbol オブジェクト）
function aboutText(sym) {
  if (!sym) return "";
  const t = sym.ticker;
  if (ABOUT[t]) return ABOUT[t];
  const sec = sym.sector;
  if (sec && SECTOR_NOTE[sec]) {
    return `${SECTOR_NOTE[sec]}（この銘柄の詳しい事業は、下の「関連ニュース」や社名でも確認できます）`;
  }
  if (sec) return `${sec}の銘柄です。詳しい事業は「関連ニュース」や社名で確認できます。`;
  return "";
}
window.aboutText = aboutText;
